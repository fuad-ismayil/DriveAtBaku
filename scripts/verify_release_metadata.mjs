import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(path, 'utf8');
const version = JSON.parse(read('package.json')).version;
assert.equal(JSON.parse(read('package-lock.json')).version, version);
assert.equal(JSON.parse(read('package-lock.json')).packages[''].version, version);
const shared = JSON.parse(read('shared/release.json'));
assert.equal(shared.version, version);
assert.deepEqual(JSON.parse(read('public/release.json')), shared);
assert.equal(shared.releaseUrl, 'https://github.com/fuad-ismayil/DriveAtBaku/releases/latest');
assert.ok(read('android/game/project.godot').includes(`config/version="${version}"`));
assert.ok(read('android/game/scripts/build_info.gd').includes(`const LABEL = "v${version}"`));
const presets = read('android/game/export_presets.cfg');
const code = version.split('.').reduce((sum, value, index) => sum + Number(value) * [10000, 100, 1][index], 0);
const names = [...presets.matchAll(/^version\/name="([^"]+)"/gm)];
assert.ok(names.length >= 2);
for (const name of names) assert.equal(name[1], version);
for (const match of presets.matchAll(/^version\/code=(\d+)/gm)) assert.equal(Number(match[1]), code);
const html = read('index.html');
assert.match(html, /id="mobile-download"(?![^>]*\bhidden\b)/);
assert.match(html, /id="loading" hidden/);
assert.doesNotMatch(html, /class="loading-scene[^\"]*"[^>]*\bsrc=/);
assert.doesNotMatch(html, /rel="(?:preload|prefetch)"[^>]*(?:\.webp|generated|main\.js)/);
console.log(`Release metadata: v${version}, Android code ${code}, ${names.length} presets, shared labels and download-only HTML fallback passed.`);
